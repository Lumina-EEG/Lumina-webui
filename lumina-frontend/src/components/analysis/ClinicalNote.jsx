import { useState } from 'react';
import { motion } from 'framer-motion';
import { Copy, Download, Check, Clock, Stethoscope } from 'lucide-react';
import Card from '../ui/Card';

export default function ClinicalNote({ note }) {
  const [copied, setCopied] = useState(false);

  if (!note) {
    return (
      <Card variant="glass">
        <div style={{ textAlign: 'center', padding: '40px 20px' }}>
          <Stethoscope size={32} color="var(--text-muted)" style={{ marginBottom: 12, opacity: 0.4 }} />
          <p style={{ color: 'var(--text-muted)', fontSize: 14 }}>
            No clinical interpretation available.
          </p>
        </div>
      </Card>
    );
  }

  const handleCopy = async () => {
    try {
      await navigator.clipboard.writeText(note);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch { /* clipboard unavailable */ }
  };

  const handleDownload = () => {
    const blob = new Blob([note], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `lumina-clinical-report-${Date.now()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const formatNote = (text) => {
    return text
      .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
      .replace(/\n{2,}/g, '\n\n')
      .split('\n').map((line, i) => {
        if (line.trim() === '') return null;
        const trimmed = line.trim();
        if (trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
          return (
            <li key={i} style={{ marginBottom: 6, color: 'var(--text-secondary)', lineHeight: 1.6 }}>
              {trimmed.substring(2)}
            </li>
          );
        }
        if (trimmed.startsWith('#')) {
          return (
            <h4 key={i} style={{ fontSize: 14, fontWeight: 600, color: 'var(--text-primary)', marginTop: 16, marginBottom: 8 }}>
              {trimmed.replace(/^#+\s*/, '')}
            </h4>
          );
        }
        return (
          <p key={i} style={{ marginBottom: 8, color: 'var(--text-secondary)', lineHeight: 1.7, fontSize: 13.5 }}>
            {trimmed}
          </p>
        );
      });
  };

  return (
    <Card variant="glass">
      <div
        style={{
          display: 'flex',
          alignItems: 'center',
          justifyContent: 'space-between',
          marginBottom: 16,
          paddingBottom: 12,
          borderBottom: '1px solid var(--border)',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
          <Stethoscope size={18} color="var(--accent)" />
          <div>
            <h3 style={{ fontSize: 15, fontWeight: 600, color: 'var(--text-primary)' }}>
              AI Clinical Interpretation
            </h3>
            <div style={{ display: 'flex', alignItems: 'center', gap: 4, marginTop: 2 }}>
              <Clock size={11} color="var(--text-muted)" />
              <span style={{ fontSize: 11, color: 'var(--text-muted)' }}>
                Generated by Lumina AI · {new Date().toLocaleString()}
              </span>
            </div>
          </div>
        </div>

        <div style={{ display: 'flex', gap: 6 }}>
          <motion.button
            whileHover={{ scale: 1.05 }}
            whileTap={{ scale: 0.95 }}
            onClick={handleCopy}
            style={{
              display: 'flex',
              alignItems: 'center',
              gap: 6,
              padding: '6px 12px',
              borderRadius: 'var(--radius-sm)',
              background: copied ? 'var(--success-dim)' : 'var(--bg-primary)',
              border: `1px solid ${copied ? 'rgba(52,211,153,0.2)' : 'var(--border)'}`,
              color: copied ? 'var(--success)' : 'var(--text-secondary)',
              cursor: 'pointer',
              fontSize: 12,
              fontWeight: 500,
              transition: 'background 0.2s, color 0.2s',
            }}
          >
            {copied ? <Check size={14} /> : <Copy size={14} />}
            {copied ? 'Copied' : 'Copy'}
          </motion.button>
          <motion.button
            whileHover={{ scale: 1.05 }}
            whileTap={{ scale: 0.95 }}
            onClick={handleDownload}
            style={{
              display: 'flex',
              alignItems: 'center',
              gap: 6,
              padding: '6px 12px',
              borderRadius: 'var(--radius-sm)',
              background: 'var(--bg-primary)',
              border: '1px solid var(--border)',
              color: 'var(--text-secondary)',
              cursor: 'pointer',
              fontSize: 12,
              fontWeight: 500,
              transition: 'background 0.2s',
            }}
          >
            <Download size={14} />
            Download
          </motion.button>
        </div>
      </div>

      <div
        style={{
          maxHeight: 320,
          overflowY: 'auto',
          paddingRight: 4,
        }}
        className="scrollable-note"
      >
        <div>{formatNote(note)}</div>
      </div>
    </Card>
  );
}
